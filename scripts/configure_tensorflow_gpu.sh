#!/usr/bin/env bash
# Configure project-local TensorFlow CUDA library discovery for Linux + NVIDIA.
set -euo pipefail

repo_root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
python_bin="$repo_root/.venv/bin/python"

if [[ ! -x "$python_bin" ]]; then
  echo "Missing $python_bin. Run 'uv sync --locked' from the repository root first." >&2
  exit 1
fi

tensorflow_dir=$("$python_bin" -c 'import os, tensorflow; print(os.path.dirname(tensorflow.__file__))')
site_packages=$(dirname "$tensorflow_dir")
cuda_libs=("$site_packages"/nvidia/*/lib/*.so*)

if [[ ! -e "${cuda_libs[0]}" ]]; then
  echo "TensorFlow CUDA libraries are absent. Confirm tensorflow[and-cuda] is installed." >&2
  exit 1
fi

# TensorFlow documents links from its package directory to its pip-installed CUDA libraries.
for library in "${cuda_libs[@]}"; do
  link="$tensorflow_dir/$(basename "$library")"
  target=$(realpath --relative-to="$tensorflow_dir" "$library")
  ln -sfn "$target" "$link"
done

mkdir -p "$repo_root/.vscode"
cat > "$repo_root/.vscode/tensorflow-gpu.env" <<EOF
# Generated by scripts/configure_tensorflow_gpu.sh; do not commit.
LD_LIBRARY_PATH=$tensorflow_dir
EOF

export LD_LIBRARY_PATH="$tensorflow_dir${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"
"$python_bin" - <<'PY'
import tensorflow as tf

gpus = tf.config.list_physical_devices("GPU")
print(f"TensorFlow GPU devices: {gpus}")
if not gpus:
    raise SystemExit("No GPU found. Check the NVIDIA driver with nvidia-smi.")
PY

echo "GPU environment configured. Restart the VS Code notebook kernel before running it."
